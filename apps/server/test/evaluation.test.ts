import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildApp } from '../src/app.ts';
import type { EvaluationRecord } from '../../../packages/protocol/src/index.ts';
import { strategyScope } from '../../../packages/agent/src/policy.ts';
const card = { name: '合成基础', kind: 'pokemon' as const, hp: 60, types: [], stage: '基础', abilities: [], attacks: [], weaknesses: [], resistances: [], retreatCost: 0 };
const deck = { cards: [{ count: 60, card }] };
test('手动 A/B 固定起点、对手、配置；仅显式请求开局，不写回策略；重启仍可比较', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'ptcg-evaluation-'));
  let app = await buildApp({ dataDir: dir, systemDir: join(dir, 'system') });
  t.after(async () => { await app.close(); await rm(dir, { recursive: true, force: true }); });
  const starts: string[] = []; app.gameService.start = match => { starts.push(match.state.id); };
  for (const id of ['one','two']) await app.gameService.opponents.save({ schemaVersion: 1, id, deck, strategies: [1,2].map(version => ({ version, content: `计划${version}`, createdAt: '2026-10-30', source: { kind: 'initial' as const }, policy: { schemaVersion: 1 as const, scope: strategyScope(deck, app.gameService.rulesText()), plan: `完整计划${version}`, entries: [] } })) });
  const before = await app.gameService.opponents.list();
  const request = { players: [{ opponentId: 'one', version: 1 }, { opponentId: 'two', version: 1 }], evaluatedPlayer: 'A' };
  const first = await app.inject({ method: 'POST', url: '/api/evaluations', payload: request });
  assert.equal(first.statusCode, 200, first.body); const record = first.json<EvaluationRecord>();
  assert.equal(starts.length, 1); assert.equal(record.comparisons.length, 0); assert.equal(JSON.stringify(record).includes('seed'), false);
  const baseline = app.gameService.match(record.baseline.matchId);
  const premature = await app.inject({ method:'POST',url:`/api/evaluations/${record.id}/comparisons`,payload:{version:2} }); assert.equal(premature.statusCode,409);
  const initial = structuredClone(baseline.records[0]!);
  await baseline.command(baseline.state.flow.operator, { requestId:'first-a',revision:baseline.state.revision,command:{kind:'choose_first',firstPlayer:'A'} });
  const dealt = structuredClone(baseline.state);
  await baseline.command(baseline.state.flow.operator, { requestId: 'end-a', revision: baseline.state.revision, command: { kind: 'concede' } });
  await app.close(); app = await buildApp({ dataDir: dir, systemDir: join(dir, 'system') }); app.gameService.start = match => { starts.push(match.state.id); };
  const second = await app.inject({ method: 'POST', url:`/api/evaluations/${record.id}/comparisons`, payload:{version:2} }); assert.equal(second.statusCode,200,second.body);
  const comparison = second.json<EvaluationRecord>(); assert.equal(starts.length, 2);
  const match = app.gameService.match(comparison.comparisons[0]!.matchId);
  assert.deepEqual({ ...match.records[0]!.state, id: initial.state.id }, initial.state);
  assert.deepEqual(match.meta.strategies.B, initial.meta.strategies.B); assert.equal(match.meta.strategies.A!.version, 2);
  assert.deepEqual(match.meta.prompts, initial.meta.prompts); assert.deepEqual(match.meta.model,initial.meta.model);
  assert.deepEqual(match.records[1]!.state.flow, baseline.records[1]!.state.flow);
  await match.command(match.state.flow.operator,{requestId:'first-b',revision:match.state.revision,command:{kind:'choose_first',firstPlayer:'A'}});
  assert.deepEqual({...match.state,id:dealt.id},dealt,'双方初次洗牌及起手手牌完全相同');
  assert.equal(JSON.stringify(await match.observe(match.state.id,'A',null)).includes('scoped-hmac-v1'),false,'私有随机状态不能进入玩家观察');
  assert.deepEqual(await app.gameService.opponents.list(), before);
  await app.inject('/api/evaluations'); await app.inject(`/api/evaluations/${record.id}`); assert.equal(starts.length,2);
  const bad = await app.inject({method:'POST',url:`/api/evaluations/${record.id}/comparisons`,payload:{version:999}}); assert.equal(bad.statusCode,400);
});

